"""
data/equipment/tiered_kits.py

Loader and selector for the new pre-built full equipment kits
generated by the "set programs" (generate_budget_tiers.py).

These are complete, rule-compliant kits (weapons + layered armor + horse + barding)
organized in 10 wealth tiers matching the starting capital scale.

Best strategy integration:
- Use these as the *primary* source of equipment for characters.
- Selection (updated rule):
  - The tier/file chosen is the one whose range *contains* the starting capital.
    Examples: 150 sp → 101-200sp ; 543 sp → 401-700sp.
  - Then, inside that tier/file, choose the set whose cost ([Nsp] value listed
    in the file, e.g. [142sp]) is the *closest* to the character's starting capital.
    Tie-break: prefer <= capital (no overspend) when distances equal.
    No random, no higher tier.
- Decompose the chosen kit into the existing Phase1/2/3 columns for compatibility.
- Fall back to the old phased system (weapon_kits + armor_sets + remaining_equipment)
  only for very poor characters where no good prebuilt kit fits.

The compact .txt files are easy to parse and contain the full item list for a kit.
"""

